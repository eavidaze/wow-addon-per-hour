-- Run from the repository root with Lua 5.1: lua tests/forever.lua
local t = assert(loadfile("tests/forever-fixture.lua"))()
local equal,near,event,tick=t.equal,t.near,t.event,t.tick
local function fresh()
    t.reply,t.played,t.characterID,t.characterName,t.characterSurname,t.realm=nil,nil,nil,nil,nil,nil
    return t.fresh()
end
local function loot(id,count)
    event("CHAT_MSG_LOOT",string.format(LOOT_ITEM_SELF_MULTIPLE,t.gold.link(id),count or 1))
end
local function run() PerHour.Session:Start(); return PerHour.Session end
local function copy(value) return PerHour.Copy(value) end

