return function(test)
    local equal, near, event, tick, click = test.equal, test.near, test.event, test.tick, test.click
    local fixture = test.fixture
    test.fresh()
    local gold, details = PerHour.Modules.Gold, PerHour.GoldDetailsPanel
    equal(details.Frame, nil, "Details is created only when requested")
    for name, module in pairs(PerHour.Modules) do
        module.View.OptionsButton:GenerateMenu()
        local items = module.View.OptionsButton.menuDescription.items
        equal(items[1].text, "Reset", name .. " keeps Reset first")
        equal(items[2].text, "Settings", name .. " keeps Settings second")
        equal(items[3].text, name == "Gold" and "Details" or "Announce", name .. " offers Details only for Gold")
        equal(#items, name == "Gold" and 4 or 3, name .. " has the expected Options actions")
    end
    gold.View.OptionsButton.menuDescription.items[3].callback()
    local frame = details.Frame
    equal(frame:IsShown(), true, "Gold Details menu opens its panel")
    equal(frame.TitleText:GetText(), "Gold Details", "Details has its own title")
    equal(frame.TitleBox.template, "DialogHeaderTemplate", "Details shares the native Settings title box")
    equal(frame.Border.template, "DialogBorderTranslucentTemplate", "Details shares the Settings border")
    equal(frame.CloseButton:GetAlpha(), 1, "Details keeps the standard close button visible")
    equal(frame:GetWidth(), 560, "compact Details matches the width of Settings")
    equal(details.ScrollBox.template, "WowScrollBoxList", "history uses the native virtualized list")
    equal(details.ScrollBar.template, "MinimalScrollBar", "history uses the native scrollbar")
    equal(frame:GetScript("OnUpdate"), nil, "Details has no per-frame polling")
    equal(details.Empty:IsShown(), true, "empty history has a visible explanation")
    equal(details.Income:GetText(), GetMoneyString(0, true), "empty income is zero")
    equal(details.Expenses:GetText(), GetMoneyString(0, true), "empty expenses are zero")
    equal(details.Net:GetText(), GetMoneyString(0, true), "empty net is zero")
    equal(frame.events.GET_ITEM_INFO_RECEIVED, true, "visible Details listens for item metadata")
    frame.Actions.close:Click()
    equal(frame:IsShown(), false, "footer Close hides Details")
    equal(frame.events.GET_ITEM_INFO_RECEIVED, nil, "hidden Details stops listening for item metadata")

    local tracker = gold.View.Frame
    tracker:Show()
    local restoreCursor = test.pointAt(tracker)
    tracker.scripts.OnEnter(tracker)
    equal(GameTooltip.singleLines[#GameTooltip.singleLines], "Left-click: Details", "Gold tooltip explains the direct Details shortcut")
    test.mouseClick(gold.View.RateFrame, "RightButton")
    equal(frame:IsShown(), false, "right-clicking the tracker does not open Details")
    equal(test.mouseDrag(gold.View.RateFrame, 0, 0), true, "rate display still routes drag gestures to Gold")
    tracker.scripts.OnMouseUp(tracker, "LeftButton")
    equal(frame:IsShown(), false, "releasing a completed drag does not open Details")
    test.mouseClick(gold.View.RateFrame, "LeftButton")
    equal(frame:IsShown(), true, "left-click reaches the tracker through the rate display and opens Details")
    equal(details.Frame, frame, "tracker click and Options share the same Details panel")
    equal(GameTooltip:IsShown(), false, "opening Details dismisses the tracker tooltip")
    equal(gold.State.HasStarted, false, "opening Details does not start tracking")
    frame:Hide()
    test.mouseClick(gold.View.OptionsButton, "LeftButton")
    equal(frame:IsShown(), false, "Options keeps its own click instead of opening Details")
    test.mouseClick(gold.View.ToggleStartButton, "LeftButton")
    equal(gold.State.HasStarted, true, "Start keeps its own click action")
    equal(frame:IsShown(), false, "starting Gold does not open Details")
    BaseModule:ResetModule(gold)
    tracker:Hide()
    restoreCursor()

    fixture.items[501] = { price = 50, class = 7 }
    fixture.items[502] = { price = 15, class = 7, available = false }
    click(gold)
    event("QUEST_TURNED_IN", 1001, 0, 10000)
    event("CHAT_MSG_LOOT", string.format(LOOT_ITEM_PUSHED_SELF_MULTIPLE, fixture.link(501), 2))
    event("QUEST_LOOT_RECEIVED", 1001, fixture.link(501), 2)
    fixture.repairCost = 300
    RepairAllItems(false)
    fixture.money = fixture.money - 300
    event("PLAYER_MONEY")
    equal(details.Frame, frame, "hidden history changes do not recreate the panel")
    equal(details.RefreshScheduled, nil, "hidden Details schedules no repaint")
    details:Show()
    equal(details.Frame, frame, "reopening reuses the Details panel")
    equal(details.Income:GetText(), GetMoneyString(10100, true), "summary adds quest money and vendor-valued rewards")
    equal(details.Expenses:GetText(), GetMoneyString(300, true), "summary separates outgoing expenses")
    equal(details.Net:GetText(), GetMoneyString(9800, true), "summary shows estimated net income")
    equal(details.Empty:IsShown(), false, "nonempty history hides the empty message")
    local function rowFor(predicate)
        local found
        details.ScrollBox:ForEachFrame(function(row) if predicate(row.Entry) then found = row end end)
        assert(found, "expected visible history row")
        return found
    end
    local repair = rowFor(function(entry) return entry.source == "repair" end)
    equal(details.ScrollBox.pool[1].Entry, repair.Entry, "newest entry is displayed first")
    equal(repair.Icon.iconTexture, "Interface\\Icons\\Trade_BlackSmithing", "repair uses native anvil artwork")
    equal(repair.Amount:GetText(), GetMoneyString(300, true), "outgoing value has no sign")
    for _, value in ipairs({ details.Income, details.Expenses, details.Net }) do
        equal(value.point[4], repair.Amount.point[4], "summary amounts share the event Value column")
        equal(value:GetWidth(), repair.Amount:GetWidth(), "summary and event amounts use the same column width")
        equal(value.justifyH, "RIGHT", "summary amounts align on the right with event values")
        local label = value:GetParent().Label
        equal(label.template, repair.Name.template, "summary labels share the normal event font size")
        equal(label.point[4], repair.Event.point[4], "summary labels share the event text indentation")
        equal(label.justifyH, "LEFT", "summary labels align on the left like event text")
    end
    equal(details.Income:GetParent().Label:GetText(), "Loot & rewards", "income label identifies the included sources")
    equal(details.Expenses:GetParent().Label:GetText(), "Expenses & items used", "expenses label includes money costs and spent item value")
    equal(details.Net:GetParent().Label:GetText(), "Estimated net profit", "profit label identifies the estimated net result")
    equal(table.concat(details.Income.textColor, ","), table.concat(PerHour.Theme.text, ","), "summary income uses normal DS white")
    equal(table.concat(details.Expenses.textColor, ","), table.concat(PerHour.Theme.red.text, ","), "summary expenses use DS red")
    equal(repair.Time:GetText(), date("%H:%M:%S", repair.Entry.timestamp), "event time shows the local clock instead of session duration")
    equal(table.concat(repair.Amount.textColor, ","), table.concat(PerHour.Theme.red.text, ","), "outgoing amount uses DS red")
    equal(repair.Direction.texture, "Interface\\Buttons\\UI-ScrollBar-ScrollDownButton-Up", "outgoing entry has a native down arrow")
    equal(repair.Direction.layer, "BACKGROUND", "direction arrow sits behind the event icon")
    equal(table.concat(repair.Direction.vertexColor, ","), table.concat(PerHour.Theme.red.text, ","), "outgoing arrow uses DS red")
    local item = rowFor(function(entry) return entry.itemID == 501 end)
    equal(item.Icon.kind, "ItemButton", "item uses the native item-button type")
    near(item.Icon:GetWidth() * item.Icon:GetScale(), 18.5, "item button uses half-size native artwork")
    equal(item.Icon.qualityItem, fixture.link(501), "native item styling uses the complete hyperlink")
    equal(item.Icon.iconTexture, C_Item.GetItemIconByID(501), "item uses its native icon")
    equal(table.concat(item.Amount.textColor, ","), table.concat(PerHour.Theme.text, ","), "incoming amount uses normal DS text")
    equal(item.Direction.texture, "Interface\\Buttons\\UI-ScrollBar-ScrollUpButton-Up", "incoming entry has a native up arrow")
    equal(table.concat(item.Direction.vertexColor, ","), table.concat(PerHour.Theme.green.text, ","), "incoming arrow uses DS green")
    equal(item.Name:GetText(), "Item 501 x2", "event combines localized item name and stack quantity")
    equal(rawget(item, "Quantity"), nil, "quantity has no separate column")
    equal(rawget(item, "Origin"), nil, "origin has no separate column or second line")
    equal(item.Event.point[5], 0, "event is centered on one line")
    equal(item.Quest:IsShown(), true, "known quest reward has an explicit quest marker")
    equal(item.Quest.Icon.atlas, "QuestNormal", "quest marker uses the native exclamation atlas")
    equal(item.Quest:GetWidth() > item.Quest.Icon:GetWidth(), true, "quest marker has a wider hover target than its artwork")
    equal(repair.Quest:IsShown(), false, "non-quest event has no misleading quest marker")
    equal(item.Event.point[4], repair.Event.point[4], "names stay aligned with or without a quest marker")
    local reward = rowFor(function(entry) return entry.source == "quest_money" end)
    equal(reward.Quest:IsShown(), true, "quest money also exposes the quest marker")
    equal(reward.Name:GetText(), "Reward", "quest marker avoids repeating quest in the money label")
    equal(reward.Icon.iconTexture, "Interface\\Icons\\INV_Misc_Bag_10", "quest money uses the native loot pouch")
    reward.Quest.scripts.OnEnter(reward.Quest)
    equal(GameTooltip.hyperlink, "quest:1001", "money marker opens the associated quest tooltip")
    reward.Icon.scripts.OnEnter(reward.Icon)
    equal(GameTooltip:IsShown(), true, "quest money pouch has a monetary tooltip")
    equal(GameTooltip:GetText(), "Quest reward", "quest money tooltip identifies its source")
    equal(GameTooltip.singleLines[1], GetMoneyString(10000, true), "quest money tooltip shows the recorded value")
    equal(GameTooltip:IsOwned(reward.Icon), true, "quest money tooltip belongs only to the pouch")
    equal(reward.Event:GetScript("OnEnter"), nil, "quest money label is passive")
    item.Icon.scripts.OnEnter(item.Icon)
    equal(GameTooltip.hyperlink, fixture.link(501), "icon opens the standard item hyperlink tooltip")
    equal(GameTooltip:IsOwned(item.Icon), true, "item tooltip belongs to the item icon")
    item.Icon.scripts.OnLeave(item.Icon)
    equal(item.Event:GetScript("OnEnter"), nil, "item text has no tooltip handler")
    equal(item.Event:IsMouseMotionEnabled(), false, "item text remains passive")
    equal(GameTooltip:IsShown(), false, "leaving the icon for item text hides the item tooltip")
    item.Quest.scripts.OnEnter(item.Quest)
    equal(GameTooltip.hyperlink, "quest:1001", "quest marker opens the standard quest tooltip")
    equal(GameTooltip:IsOwned(item.Quest), true, "quest tooltip belongs to the explicit quest marker")
    item.Quest.scripts.OnLeave(item.Quest)
    equal(GameTooltip:IsShown(), false, "leaving a history tooltip hides it")
    repair.Icon.scripts.OnEnter(repair.Icon)
    equal(GameTooltip:IsShown(), false, "repair icon has no tooltip")
    equal(repair.Event:GetScript("OnEnter"), nil, "non-item event labels have no tooltip")
    item.Icon.scripts.OnEnter(item.Icon)
    equal(GameTooltip:IsShown(), true, "item tooltip remains available")
    frame.CloseButton:Click()
    equal(GameTooltip:IsShown(), false, "closing Details also hides its tooltip")
    equal(gold.State.HasStarted and not gold.State.HasPaused, true, "closing Details keeps Gold tracking active")
    details:Show()

    event("CHAT_MSG_LOOT", string.format(LOOT_ITEM_PUSHED_SELF_MULTIPLE, fixture.link(502), 2))
    equal(details.RefreshScheduled, true, "history changes request a deferred visible repaint")
    tick(0)
    local pending = rowFor(function(entry) return entry.itemID == 502 end)
    local pickupTime = pending.Time:GetText()
    equal(pending.Amount:GetText(), "Pending", "unresolved item has a clear pending amount")
    equal(table.concat(pending.Amount.textColor, ","), table.concat(PerHour.Theme.text, ","), "pending amount clears the reused row's outgoing color")
    equal(details.Pending:GetText(), "Pending prices: 1", "summary exposes pending entries")
    equal(details.Income:GetText(), GetMoneyString(10100, true), "pending value is not added speculatively")
    pending.Icon.scripts.OnEnter(pending.Icon)
    click(gold)
    tick(5)
    fixture.items[502].available = true
    event("GET_ITEM_INFO_RECEIVED", 502, true)
    tick(0)
    pending = rowFor(function(entry) return entry.itemID == 502 end)
    equal(pending.Amount:GetText(), GetMoneyString(30, true), "incoming value has no sign after price settlement")
    equal(pending.Time:GetText(), pickupTime, "delayed price settlement retains the original event clock time")
    equal(pending.Name:GetText(), "Item 502 x2", "loaded metadata replaces the placeholder and preserves quantity")
    equal(details.Pending:GetText(), "", "resolved history clears pending summary")
    equal(details.Income:GetText(), GetMoneyString(10130, true), "summary includes the settled price once")
    equal(GameTooltip:IsShown(), true, "metadata refresh preserves a tooltip on the same visible event")
    equal(GameTooltip.hyperlink, fixture.link(502), "loaded item retains its standard tooltip")
    click(gold)
    event("CHAT_MSG_LOOT", string.format(LOOT_ITEM_PUSHED_SELF_MULTIPLE, fixture.link(502), 1))
    tick(0)
    event("QUEST_LOOT_RECEIVED", 1002, fixture.link(502), 1)
    tick(0)
    pending = rowFor(function(entry) return entry.itemID == 502 and entry.quantity == 1 end)
    equal(pending.Name:GetText(), "Item 502", "single item has no redundant x1 suffix")
    equal(pending.Event:GetScript("OnEnter"), nil, "late quest metadata does not add a tooltip to item text")
    equal(pending.Quest:IsShown(), true, "late quest metadata reveals its quest marker")
    pending.Quest.scripts.OnEnter(pending.Quest)
    equal(GameTooltip.hyperlink, "quest:1002", "late quest metadata is available from its marker")

    local originalRefresh, refreshes = details.Refresh, 0
    details.Refresh = function(self, ...)
        refreshes = refreshes + 1
        return originalRefresh(self, ...)
    end
    for _ = 1, 200 do event("CHAT_MSG_MONEY", "You loot 1 Copper") end
    equal(refreshes, 0, "event burst defers history rendering")
    tick(0)
    equal(refreshes, 1, "one deferred refresh renders the complete event burst")
    details.Refresh = originalRefresh
    equal(#details.ScrollBox.elements, #gold.State.History, "data provider contains the complete session history")
    equal(#details.ScrollBox.pool <= 13, true, "large history creates only a bounded reusable viewport")
    local staleQuestMarker = false
    details.ScrollBox:ForEachFrame(function(row)
        if row.Quest:IsShown() then staleQuestMarker = true end
    end)
    equal(staleQuestMarker, false, "recycled ordinary loot rows do not retain old quest markers")
    equal(details.ScrollBox.pool[1].Direction.texture, "Interface\\Buttons\\UI-ScrollBar-ScrollUpButton-Up", "recycled incoming row clears an outgoing arrow")
    equal(table.concat(details.ScrollBox.pool[1].Amount.textColor, ","), table.concat(PerHour.Theme.text, ","), "recycled incoming row clears outgoing red")
    details.ScrollBox:ScrollToOffset(5 * 26 + 7)
    local anchor = details.ScrollBox.pool[1].Entry
    local offset = details.ScrollBox:GetDerivedScrollOffset()
    event("CHAT_MSG_MONEY", "You loot 2 Copper")
    event("CHAT_MSG_MONEY", "You loot 3 Copper")
    tick(0)
    near(details.ScrollBox:GetDerivedScrollOffset(), offset + 2 * 26, "new entries preserve the reader's pixel position")
    equal(details.ScrollBox.pool[1].Entry, anchor, "new entries keep the same older event under review")
    offset = details.ScrollBox:GetDerivedScrollOffset()
    event("QUEST_DATA_LOAD_RESULT", 1001, true)
    tick(0)
    near(details.ScrollBox:GetDerivedScrollOffset(), offset, "metadata updates do not move the scroll position")
    frame:Hide()
    event("CHAT_MSG_MONEY", "You loot 4 Copper")
    details:Show()
    equal(details.ScrollBox.pool[1].Entry, anchor, "reopening preserves an older-event anchor across hidden gains")
    details.ScrollBox:ScrollToOffset(0)
    event("CHAT_MSG_MONEY", "You loot 5 Copper")
    tick(0)
    near(details.ScrollBox:GetDerivedScrollOffset(), 0, "reader at top follows the newest events")
    equal(details.ScrollBox.pool[1].Entry, gold.State.History[#gold.State.History], "top shows the latest event")
    local allocated = #details.ScrollBox.pool
    frame:Hide()
    details:Show()
    equal(#details.ScrollBox.pool, allocated, "reopening creates no duplicate row pool")

    local top = details.ScrollBox.pool[1]
    equal(top.Name:GetText(), "Looted", "looted money uses the shorter event label")
    equal(top.Icon.iconTexture, "Interface\\Icons\\INV_Misc_Bag_10", "looted money uses the native loot pouch")
    top.Icon.scripts.OnEnter(top.Icon)
    equal(GameTooltip:IsShown(), true, "looted money pouch shows its value on hover")
    equal(GameTooltip:GetText(), "Looted money", "looted money tooltip identifies its source")
    equal(GameTooltip.singleLines[1], GetMoneyString(top.Entry.amount, true), "looted money tooltip shows the recorded value")
    top.Icon.scripts.OnLeave(top.Icon)
    equal(GameTooltip:IsShown(), false, "leaving the pouch hides the money tooltip")
    BaseModule:ResetModule(gold)
    tick(0)
    equal(details.Empty:IsShown(), true, "Reset clears the open history view")
    equal(details.Net:GetText(), GetMoneyString(0, true), "Reset clears the visible summary")
    equal(GameTooltip:IsShown(), false, "Reset cannot leave a tooltip for a removed entry")
    equal(#details.ScrollBox.elements, 0, "Reset drops stale provider entries")
    near(details.ScrollBox:GetDerivedScrollOffset(), 0, "Reset restores the top position")
    click(gold)
    fixture.repairCost = 50
    RepairAllItems(false)
    fixture.money = fixture.money - 50
    event("PLAYER_MONEY")
    tick(0)
    equal(details.Net:GetText(), "- " .. GetMoneyString(50, true), "summary supports a spaced negative estimated net")
    event("PLAYER_LOGOUT")
    local saved = test.copy(PerHourCharacter_Values)
    local savedTimestamp = saved.sessions.Gold.context.history[1].timestamp
    test.login(saved, 0)
    details = PerHour.GoldDetailsPanel
    equal(details.Frame, nil, "reload leaves Details lazy")
    details:Show()
    equal(details.Net:GetText(), "- " .. GetMoneyString(50, true), "reopened Details reads restored journal")
    equal(#details.ScrollBox.elements, 1, "reload shows saved history rather than old UI data")
    equal(details.ScrollBox.pool[1].Time:GetText(), date("%H:%M:%S", savedTimestamp), "reload retains the event's original clock time")
    saved.sessions.Gold.context.history[1].timestamp = nil
    test.login(saved, 0)
    PerHour.GoldDetailsPanel:Show()
    equal(PerHour.GoldDetailsPanel.ScrollBox.pool[1].Time:GetText(), "—", "older events without timestamps show an unknown time without backfill")
    test.fresh()
    PerHour.GoldDetailsPanel:Show()
    equal(PerHour.GoldDetailsPanel.Empty:IsShown(), true, "another character does not inherit history view contents")

    details, gold = PerHour.GoldDetailsPanel, PerHour.Modules.Gold
    fixture.items[503] = { price = 0, available = false }
    click(gold)
    event("CHAT_MSG_LOOT", string.format(LOOT_ITEM_PUSHED_SELF_MULTIPLE, fixture.link(503), 1))
    for _ = 1, 20 do event("CHAT_MSG_MONEY", "You loot 1 Copper") end
    tick(0)
    details.ScrollBox:ScrollToOffset(5 * 26 + 7)
    anchor = details.ScrollBox.pool[1].Entry
    offset = details.ScrollBox:GetDerivedScrollOffset()
    fixture.items[503].available = true
    event("GET_ITEM_INFO_RECEIVED", 503, true)
    tick(0)
    equal(#details.ScrollBox.elements, 20, "resolved zero-value item disappears from Details")
    near(details.ScrollBox:GetDerivedScrollOffset(), offset, "removing a valueless item below the reader does not move the viewport")
    equal(details.ScrollBox.pool[1].Entry, anchor, "reader keeps the same entry after removal below the anchor")
    fixture.items[504] = { price = 0, available = false }
    event("CHAT_MSG_LOOT", string.format(LOOT_ITEM_PUSHED_SELF_MULTIPLE, fixture.link(504), 1))
    tick(0)
    fixture.items[504].available = true
    event("GET_ITEM_INFO_RECEIVED", 504, true)
    tick(0)
    near(details.ScrollBox:GetDerivedScrollOffset(), offset, "adding then discarding a pending item above the reader restores the original offset")
    equal(details.ScrollBox.pool[1].Entry, anchor, "reader keeps the same entry after removal above the anchor")
    equal(details.Pending:GetText(), "", "discarded zero-value items clear pending summary")
    equal(details.Net:GetText(), GetMoneyString(20, true), "discarded zero-value items do not affect summary totals")
    event("PLAYER_LOGOUT")
    local legacy = test.copy(PerHourCharacter_Values)
    local oldZero = { elapsed = 0, source = "item_reward", amount = 0, direction = 1,
        itemID = 503, itemLink = fixture.link(503), quantity = 1, unitPrice = 0 }
    table.insert(legacy.sessions.Gold.context.history, oldZero)
    test.login(legacy, 0)
    details, gold = PerHour.GoldDetailsPanel, PerHour.Modules.Gold
    details:Show()
    equal(#gold.State.History, 21, "older zero-value entries remain readable without a migration")
    equal(#details.ScrollBox.elements, 20, "Details hides older zero-value entries without rewriting the journal")
    event("PLAYER_LOGOUT")
    equal(#PerHourCharacter_Values.sessions.Gold.context.history, 21, "view filtering leaves previously saved history intact")
    legacy.sessions.Gold.context.history = { oldZero }
    legacy.sessions.Gold.total = 0
    test.login(legacy, 0)
    PerHour.GoldDetailsPanel:Show()
    equal(PerHour.GoldDetailsPanel.Empty:IsShown(), true, "history containing only old zero-value items displays the empty state")

    test.fresh()
    gold, details = PerHour.Modules.Gold, PerHour.GoldDetailsPanel
    fixture.items[505] = { price = 0, available = false }
    click(gold)
    for _ = 1, 20 do event("CHAT_MSG_LOOT", string.format(LOOT_ITEM_SELF, fixture.link(505))) end
    for _ = 1, 30 do event("CHAT_MSG_MONEY", "You loot 1 Copper") end
    details:Show()
    details.ScrollBox:ScrollToOffset(30 * 26 + 7)
    fixture.items[505].available = true
    event("GET_ITEM_INFO_RECEIVED", 505, true)
    tick(0)
    near(details.ScrollBox:GetDerivedScrollOffset(), details.ScrollBox:GetDerivedScrollRange(),
        "removing the viewed pending entries keeps the nearest surviving older section instead of jumping to the top")
end
