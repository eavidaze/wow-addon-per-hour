return function(t,fresh)
    local equal,event,tick=t.equal,t.event,t.tick
    fresh()
    t.faction(nil); tick(0)
    local dashboard=PerHour.Dashboard
    equal(dashboard.Displays[4]:IsShown(),false,"untracked reputation is hidden before Start")
    equal(select(5,dashboard.Displays[3]:GetPoint()),0,"single tertiary is vertically centered beside the primary")
    equal(dashboard.Displays[1]:GetWidth(),86,"primary is narrower without the speedometer")
    equal(dashboard.Displays[2]:GetWidth(),53,"secondary width shrinks proportionally to its font")
    for index,size in ipairs({28,18,14,14}) do
        equal(select(2,dashboard.Displays[index].Value:GetFont()),size,"compact preset value font at slot "..index)
    end
    for index,size in ipairs({12,10,10,10}) do
        equal(select(2,dashboard.Displays[index].Unit:GetFont()),size,"readable unit font at slot "..index)
    end
    equal(dashboard.Displays[3].Value:GetWidth(),0,"idle honor text uses unconstrained native sizing")
    for index,height in ipairs({29,19,15,15}) do
        equal(dashboard.Displays[index]:GetHeight(),height,"compact preset display height at slot "..index)
    end
    PerHour.SettingsPanel:Show()
    equal(PerHour.SettingsPanel.Positions[4].Metric,"Reputation","hidden reputation keeps its configurable preferred position")
    t.faction({name="Stormwind",factionID=72,currentStanding=0}); tick(0)
    equal(dashboard.Displays[4]:IsShown(),true,"selecting a faction restores reputation without starting capture")
    equal(PerHour.Session.Current,nil,"changing display eligibility leaves the session idle")
    equal(dashboard.Displays[3]:GetWidth(),dashboard.Displays[2]:GetWidth(),"tertiary and secondary share the same width")
    equal(dashboard.Duration:GetHeight(),11,"duration uses the rounded XS display height")
    equal(select(2,dashboard.Duration.Value:GetFont()),10,"duration uses a whole-pixel XS value font")
    t.near(dashboard.Frame:GetWidth(),dashboard.Displays[1]:GetWidth()+2*dashboard.Displays[2]:GetWidth()+10+30,
        "Full panel fits its three columns, gaps and content padding")
    local fullWidth=dashboard.Frame:GetWidth()
    local fullHeight=dashboard.Frame:GetHeight()
    PerHour.Stores.Settings:Set("panelType","extended"); dashboard:RefreshDisplays()
    equal(dashboard.Frame:GetWidth() < fullWidth,true,"Extended panel shrinks when the tertiary column is removed")
    equal(dashboard.Frame:GetHeight(),fullHeight,"Extended reserves the Full composition height")
    local extendedWidth=dashboard.Frame:GetWidth()
    PerHour.Stores.Settings:Set("panelType","focused"); dashboard:RefreshDisplays()
    equal(dashboard.Frame:GetWidth() <= extendedWidth,true,"Focused fits the primary while respecting the footer minimum")
    equal(dashboard.Frame:GetHeight(),fullHeight,"Focused reserves the Full composition height")
    local focusedHeight=dashboard.Frame:GetHeight()
    PerHour.Stores.Settings:SetSpeedometerEnabled(true); dashboard:RefreshDisplays()
    equal(dashboard.Displays[1]:GetWidth(),101,"speedometer restores the established primary width")
    equal(dashboard.Frame:GetHeight() > focusedHeight and dashboard.Frame:GetWidth() >= dashboard.SpeedometerArea:GetWidth()+30,
        true,"panel expands to contain the optional gauge")
    equal(dashboard.SpeedometerArea:GetWidth(),dashboard.Displays[1]:GetWidth(),
        "gauge width follows the full main display")
    local gaugeHeight=dashboard.Frame:GetHeight()
    PerHour.Stores.Settings:Set("panelType","full"); dashboard:RefreshDisplays()
    equal(dashboard.Frame:GetHeight(),gaugeHeight,"panel types keep the same height with a gauge")
    local radius=dashboard.Speedometer.Radius
    PerHour.Stores.Settings:SetSpeedometerEnabled(false); dashboard:RefreshDisplays()
    equal(dashboard.Displays[1]:GetWidth(),86,"hiding speedometer brings the side columns closer again")
    equal(dashboard.Speedometer.Radius,radius,"hiding speedometer preserves its reserved artwork geometry")

    fresh(); t.faction(nil); PerHour.Session:Start(); tick(5)
    t.faction({name="Stormwind",factionID=72,currentStanding=0}); tick(0)
    local reputationDisplay=PerHour.Dashboard.Displays[4]
    equal(reputationDisplay.Value:GetText(),"0","new watched faction shows zero before any measured faction time")
    equal(reputationDisplay.Unit:GetText(),"rep/h","empty reputation retains its rate unit")
    PerHour.Stores.Settings:SetRate("minute"); PerHour.Dashboard:RefreshDisplays()
    equal(reputationDisplay.Value:GetText(),"0","new watched faction remains zero with minute rates")
    equal(reputationDisplay.Unit:GetText(),"rep/m","empty reputation follows the minute unit")

    fresh()
    dashboard=PerHour.Dashboard
    local actionWidth,footerWidth=dashboard.Frame.Actions.primary:GetWidth(),dashboard.Frame.ActionBar:GetWidth()
    PerHour.Session:Start(); tick(3600); t.honor(27800)
    t.faction({name="Stormwind",factionID=72,currentStanding=27800}); tick(0)
    equal(dashboard.Displays[3].Value:GetText(),"27.8k","narrow honor display shows the full reading beyond its slot")
    equal(dashboard.Displays[4].Value:GetText(),"27.8k","narrow reputation display shows the full reading beyond its slot")
    equal(dashboard.Displays[3].Value:GetWidth(),0,"long honor reading retains unconstrained native sizing")
    PerHour.Session:Pause()
    equal(dashboard.Frame.Actions.primary:GetWidth(),actionWidth,"Resume preserves the fixed action width")
    equal(dashboard.Frame.ActionBar:GetWidth(),footerWidth,"Resume does not resize the footer")
    PerHour.Session:Resume()
    equal(dashboard.Frame.Actions.primary:GetWidth(),actionWidth,"Pause preserves the fixed action width")

    fresh(); PerHour.Session:Start()
    event("CHAT_MSG_MONEY","You loot 1 Gold")
    PerHour.Session:Save()
    local saved=t.copy(PerHourRevampSession)
    saved.current.modules.Gold.history[1].amount=999
    t.reload(saved,0)
    local gold=PerHour.Modules.Gold
    equal(gold.State.Disabled,true,"damaged Gold context is isolated for the current session")
    equal(gold.State.Element,10000,"readable Gold summary is preserved")
    equal(PerHour.Session.Current.paused,false,"one damaged context does not pause verified healthy capture")
    equal(PerHour.Modules.Experience.State.Partial == true,false,"Gold corruption does not mark XP partial")
    event("CHAT_MSG_MONEY","You loot 9 Gold")
    equal(gold.State.Element,10000,"damaged ledger cannot accept misleading additional Gold")
    t.honor(5)
    equal(PerHour.Modules.Honor.State.Element,5,"healthy honor still captures")
    PerHour.Session:Save(); t.reload(t.copy(PerHourRevampSession),0)
    equal(PerHour.Modules.Gold.State.Disabled,true,"isolated metric survives another reload")
    equal(PerHour.Modules.Gold.State.Element,10000,"repeated recovery preserves readable totals")
    local record=PerHour.Session:Finish()
    equal(record.metrics.Gold.incomplete,true,"damaged metric finalizes with incomplete frozen warning")
    equal(record.gold.coins,10000,"saved Gold composition remains coherent")

    fresh(); PerHour.Session:Start(); tick(10)
    t.faction({name="Stormwind",factionID=72,currentStanding=100,reaction=4,currentReactionThreshold=0,nextReactionThreshold=3000})
    t.faction({name="Stormwind",factionID=72,currentStanding={secret=true}})
    equal(PerHour.Modules.Reputation.State.Available,false,"unreadable faction event reports failure immediately")
    tick(10)
    equal(PerHour.Modules.Reputation.State.Available,false,"unreadable watched progress is unavailable")
    equal(PerHour.Modules.Reputation.State.Factions[72].partial,true,"only affected faction is marked partial")
    t.faction({name="Stormwind",factionID=72,currentStanding=200,reaction=4,currentReactionThreshold=0,nextReactionThreshold=3000})
    equal(PerHour.Modules.Reputation.State.Element,100,"unreadable reputation interval is not backfilled")
    t.faction({name="Ironforge",factionID=47,currentStanding=0,reaction=4,currentReactionThreshold=0,nextReactionThreshold=3000})
    equal(PerHour.Modules.Reputation.State.Partial,false,"healthy new faction does not inherit another faction's warning")
    record=PerHour.Session:Finish()
    equal(record.reputation[72].partial,true,"archive retains affected faction's warning")
    equal(record.reputation[47].partial == true,false,"archive keeps other faction complete")

    fresh(); PerHour.Session:Start()
    local owner=LibStub("LibDataBroker-1.1"):GetDataObjectByName("PerHour")
    owner.OnClick(PerHour.MinimapButton,"LeftButton")
    equal(PerHour.Dashboard.Frame:IsShown(),false,"broker and minimap share left-click toggle")
    owner.OnClick(PerHour.MinimapButton,"RightButton")
    equal(PerHour.SettingsPanel.Frame:IsShown(),true,"right click opens Settings")
    equal(PerHour.Session.Current.paused,false,"opening Settings leaves capture running")
    PerHour.Stores.Settings:Set("panelType","focused")
    PerHour.Stores.Settings:Set("showDuration",true)
    PerHour.Dashboard:Show()
    equal(PerHour.Dashboard.Duration:IsShown(),false,"Focused respects its duration layout")
    PerHour.Stores.Settings:Set("panelType","extended")
    PerHour.Dashboard:RefreshDisplays()
    equal(PerHour.Dashboard.Duration:IsShown(),true,"Extended uses Show duration")
    PerHour.Stores.Settings:Set("showDuration",false)
    PerHour.Dashboard:RefreshDisplays()
    equal(PerHour.Dashboard.Duration:IsShown(),false,"fresh short session does not override duration preference")
    equal(PerHour.Dashboard.Estimate:GetWidth(),PerHour.Dashboard.Displays[1]:GetWidth(),"estimate area follows the main width")
    equal(select(2,PerHour.Dashboard.Estimate.Value:GetFont()),10,"estimate uses the recalibrated XS font")
    equal(PerHour.Format:Unit("Gold"),"g/h","default rates use /h")
    PerHour.Stores.Settings:SetRate("minute")
    equal(PerHour.Format:Unit("Gold"),"g/m","minute rates use explicit /m preference")

    fresh(); PerHour.Session:Start(); PerHour.Session:Save()
    local checkpoint=t.copy(PerHourRevampSession)
    t.reload(checkpoint,120)
    equal(PerHour.Session.Current.needsReview,true,"played-time mismatch requires explicit review")
    equal(PerHour.Session.Current.paused,true,"mismatch cannot silently resume")
    PerHour.Session:Resume()
    equal(PerHour.Session.Current.paused,false,"Resume accepts preserved totals after review")
    equal(PerHour.Modules.Honor.State.Partial,true,"acknowledgement does not erase partial coverage")
end
