return function(t,fresh)
    fresh()
    local equal=t.equal
    local dashboard=PerHour.Dashboard
    local indicator=PerHour.Components:CreateSessionIndicator(dashboard.Frame.Content)
    local animation=indicator.Animation.animations[1]
    equal(animation.kind,"FlipBook","optional active indicator uses a native flipbook")
    equal(animation.duration,1.4,"optional active indicator preserves the MUI cycle")
    equal(animation.rows,8,"flipbook uses the atlas row count")
    equal(animation.columns,16,"flipbook uses the atlas column count")
    equal(animation.frames,84,"flipbook excludes unused atlas cells")
    equal(animation.frameWidth,0,"flipbook derives frame width from the atlas")
    equal(animation.frameHeight,0,"flipbook derives frame height from the atlas")
    equal(indicator.Animation:IsPlaying(),false,"inactive indicator does not spin")
    equal(indicator.PauseBars[1]:IsShown(),true,"inactive indicator shows pause bars")
    indicator:SetRunning(true)
    equal(indicator.Animation:IsPlaying(),true,"activating indicator starts native animation")
    equal(indicator.Spinner:IsShown(),true,"active indicator shows its spinner")
    local playCount=indicator.Animation.playCount
    indicator:SetRunning(true)
    equal(indicator.Animation.playCount,playCount,"repeated active state does not restart animation")
    indicator:SetRunning(false)
    equal(indicator.Animation:IsPlaying(),false,"pausing stops rotation")
    equal(indicator.PauseBars[2]:IsShown(),true,"pausing shows both bars")
    indicator:SetRunning(true)
    equal(indicator.Animation:IsPlaying(),true,"reactivating indicator starts animation")
    indicator:Hide()
    equal(indicator.Animation:IsPlaying(),false,"hidden indicator does not animate")
    indicator:Show()
    equal(indicator.Animation:IsPlaying(),true,"showing active indicator resumes animation")
    dashboard:Toggle()
    equal(indicator.Animation:IsPlaying(),false,"hidden dashboard stops the indicator")
    dashboard:Show()
    equal(indicator.Animation:IsPlaying(),true,"showing dashboard restores the active indicator")
    indicator:SetRunning(false)
    equal(indicator.Animation:IsPlaying(),false,"deactivating indicator stops animation")
    equal(indicator.PauseBars[1]:IsShown(),true,"deactivating indicator restores pause bars")
    equal(indicator:GetScript("OnUpdate"),nil,"indicator uses no per-frame Lua callback")
end
