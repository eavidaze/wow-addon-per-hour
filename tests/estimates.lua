return function(t,fresh)
    local equal,event,tick=t.equal,t.event,t.tick
    fresh()
    local xp=PerHour.Modules.Experience
    equal(BaseModule:GetEstimate(xp),"Not started","estimate before Start")
    PerHour.Session:Start()
    t.progress({xp=200}); event("PLAYER_XP_UPDATE","player"); tick(59)
    equal(BaseModule:GetEstimate(xp),"Estimating…","estimate waits one measured minute")
    tick(1)
    equal(BaseModule:GetEstimate(xp),"Level 11 in 8m","estimate uses remaining progress and exact session mean")
    PerHour.Stores.Settings:SetRate("minute")
    equal(BaseModule:GetEstimate(xp),"Level 11 in 8m","rate display unit does not change estimate")
    PerHour.Session:Pause(); tick(120)
    equal(BaseModule:GetEstimate(xp),"Paused","paused estimate is explicit")
    t.progress({xp=400}); event("PLAYER_XP_UPDATE","player")
    PerHour.Session:Resume()
    equal(BaseModule:GetEstimate(xp),"Level 11 in 6m","Resume uses current progress and prior measured mean")
    fresh(); PerHour.Session:Start(); tick(60)
    equal(BaseModule:GetEstimate(PerHour.Modules.Experience),"No estimate available","zero progress has no prediction")
    t.progress({level=60,xp=0,maximum=0}); event("PLAYER_XP_UPDATE","player")
    equal(BaseModule:GetEstimate(PerHour.Modules.Experience),"Max level reached","cap has no next objective")
    fresh(); PerHour.Session:Start(); tick(60)
    t.faction({name="Stormwind",factionID=72,currentStanding=1000,reaction=4,currentReactionThreshold=0,nextReactionThreshold=3000})
    equal(BaseModule:GetEstimate(PerHour.Modules.Reputation),"Friendly in 2m","reputation estimate uses selected faction mean")
    t.faction(nil)
    equal(BaseModule:GetEstimate(PerHour.Modules.Reputation),"No estimate available","None has no forecast")
end
