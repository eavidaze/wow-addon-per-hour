return function(t,fresh)
    local equal,event,tick=t.equal,t.event,t.tick
    fresh()
    local xp=PerHour.Modules.Experience
    equal(BaseModule:GetEstimate(xp),"Not started","estimate before Start")
    PerHour.Session:Start()
    t.progress({xp=200}); event("PLAYER_XP_UPDATE","player"); tick(59)
    equal(BaseModule:GetEstimate(xp),"Estimating…","estimate waits one measured minute")
    tick(1)
    equal(BaseModule:GetEstimate(xp),"Level 11 in 8m","estimate uses remaining progress and exact session mean")
    PerHour.Stores.Settings:SetRate("minute")
    equal(BaseModule:GetEstimate(xp),"Level 11 in 8m","rate display unit does not change estimate")
    PerHour.Session:Pause(); tick(120)
    equal(BaseModule:GetEstimate(xp),"Paused","paused estimate is explicit")
    t.progress({xp=400}); event("PLAYER_XP_UPDATE","player")
    PerHour.Session:Resume()
    equal(BaseModule:GetEstimate(xp),"Level 11 in 6m","Resume uses current progress and prior measured mean")
    fresh(); PerHour.Session:Start(); tick(60)
    equal(BaseModule:GetEstimate(PerHour.Modules.Experience),"No estimate available","zero progress has no prediction")
    t.progress({level=60,xp=0,maximum=0}); event("PLAYER_XP_UPDATE","player")
    equal(BaseModule:GetEstimate(PerHour.Modules.Experience),"Max level reached","cap has no next objective")
    fresh(); PerHour.Session:Start(); tick(60)
    t.faction({name="Stormwind",factionID=72,currentStanding=1000,reaction=4,currentReactionThreshold=0,nextReactionThreshold=3000})
    equal(BaseModule:GetEstimate(PerHour.Modules.Reputation),"Friendly in 2m","reputation estimate uses selected faction mean")
    t.faction(nil)
    equal(BaseModule:GetEstimate(PerHour.Modules.Reputation),"No estimate available","None has no forecast")

    fresh()
    local settings,panel,dashboard=PerHour.Stores.Settings,PerHour.SettingsPanel,PerHour.Dashboard
    panel:Show()
    local xpEstimate,repEstimate=dashboard.ExperienceEstimate,dashboard.ReputationEstimate
    local groups=panel.Frame.Fields
    equal(#groups[1].Fields,2,"General contains only panel type and rate")
    equal(groups[3].Fields[#groups[3].Fields],panel.ExperienceEstimates,"Experience ends with Show estimates")
    equal(groups[4].Fields[#groups[4].Fields],panel.ReputationEstimates,"Reputation ends with Show estimates")
    equal(xpEstimate:IsShown(),false,"XP estimates default off")
    equal(repEstimate:IsShown(),false,"reputation estimates default off")
    panel.ExperienceEstimates:SetValue(true)
    equal(xpEstimate:IsShown(),true,"XP checkbox shows its estimate immediately")
    equal(repEstimate:IsShown(),false,"XP checkbox does not enable reputation")
    panel.ReputationEstimates:SetValue(true)
    equal(xpEstimate:IsShown() and repEstimate:IsShown(),true,"both estimates can be shown together")
    local fullHeight=dashboard.Frame:GetHeight()
    for _,mode in ipairs({"focused","extended","full"}) do
        panel.PanelType:SetValue(mode)
        equal(xpEstimate:IsShown() and repEstimate:IsShown(),true,"both estimates remain visible in "..mode)
        equal(dashboard.Frame:GetHeight(),fullHeight,"estimates keep composition height in "..mode)
    end
    local point,relative,relativePoint,_,offset=xpEstimate:GetPoint()
    equal(point,"BOTTOM","XP estimate anchors by its bottom")
    equal(relative,dashboard.Displays[1],"XP estimate follows Primary")
    equal(relativePoint,"TOP","XP estimate sits above Primary")
    equal(offset,2,"XP estimate has a gap above Primary")
    point,relative,relativePoint,_,offset=repEstimate:GetPoint()
    equal(point,"TOP","reputation estimate anchors by its top")
    equal(relative,dashboard.Displays[1],"reputation estimate follows Primary")
    equal(relativePoint,"BOTTOM","reputation estimate sits below Primary")
    equal(offset,-2,"reputation estimate has a gap below Primary")
    panel.Gauge:SetValue(true)
    equal(dashboard.SpeedometerArea:IsShown(),true,"gauge can accompany both estimates")
    equal(select(5,dashboard.SpeedometerArea:GetPoint()) > 2+xpEstimate:GetHeight(),true,
        "XP estimate fits between Primary and speedometer")
    panel.Gauge:SetValue(false)
    local bothHeight=dashboard.Frame:GetHeight()
    panel.ReputationEstimates:SetValue(false)
    equal(dashboard.Frame:GetHeight() < bothHeight,true,"hiding reputation releases its space below Primary")
    equal(xpEstimate:IsShown(),true,"hiding reputation retains XP estimate")
    panel.ExperienceEstimates:SetValue(false); panel.ReputationEstimates:SetValue(true)
    equal(xpEstimate:IsShown(),false,"XP checkbox independently hides XP estimate")
    equal(repEstimate:IsShown(),true,"reputation can appear alone")
    panel.ExperienceEstimates:SetValue(true)
    settings:Init(); panel:Refresh()
    equal(panel.ExperienceEstimates:GetValue() and panel.ReputationEstimates:GetValue(),true,
        "both preferences survive initialization")
    PerHour.Session:Start(); tick(60)
    t.progress({xp=200}); event("PLAYER_XP_UPDATE","player")
    t.faction({name="Stormwind",factionID=72,currentStanding=1000,reaction=4,currentReactionThreshold=0,nextReactionThreshold=3000})
    dashboard:RefreshDisplays()
    equal(xpEstimate.Value:GetText(),BaseModule:GetEstimate(PerHour.Modules.Experience),"upper estimate reads XP")
    equal(repEstimate.Value:GetText(),BaseModule:GetEstimate(PerHour.Modules.Reputation),"lower estimate reads reputation")
    PerHour.Session:Pause()
    equal(xpEstimate.Value:GetText(),"Paused","XP estimate follows pause")
    equal(repEstimate.Value:GetText(),"Paused","reputation estimate follows pause")
    t.progress({level=60,xp=0,maximum=0}); event("PLAYER_XP_UPDATE","player"); tick(0)
    equal(xpEstimate:IsShown(),false,"max level hides only the XP estimate")
    equal(repEstimate:IsShown(),true,"max level keeps reputation estimate")
    equal(settings:GetEstimatesEnabled("Experience"),true,"max level preserves the XP preference")
    for _,field in ipairs(panel.Positions) do
        equal(rawget(field,"Grip"),nil,"metric rows have no drag grip")
        equal(field:GetScript("OnDragStart"),nil,"metric rows have no drag handler")
    end
    panel.Positions[1]:SetValue("Honor")
    equal(dashboard:GetConfiguredOrder()[1],"Honor","selector still swaps metrics at max level")
    panel.Positions[1].Selector.IncrementButton:Click()
    equal(dashboard:GetConfiguredOrder()[1],"Gold","right arrow still swaps metrics")
    panel.Positions[2].Selector.DecrementButton:Click()
    equal(dashboard:GetConfiguredOrder()[1],"Honor","left arrow still swaps metrics")
end
